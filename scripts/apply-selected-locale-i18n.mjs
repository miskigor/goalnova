const enPath = join(root, "messages", "en.json");
const en = JSON.parse(readFileSync(enPath, "utf8"));

for (const locale of LOCALES) {
  const file = join(root, "messages", `${locale}.json`);
  const data = JSON.parse(readFileSync(file, "utf8"));

  warnMissing(clubsMap, locale, "clubs");
  warnMissing(clubEmailsMap, locale, "clubEmails");
  warnMissing(adminSupportMap, locale, "adminSupport");
  warnMissing(adminSupportColumns, locale, "adminSupport.columns");
  warnMissing(adminSupportPriorities, locale, "adminSupport.priorities");
  warnMissing(notificationsMap, locale, "notifications");

  const clubs = pick(clubsMap, locale);
  const clubEmails = pick(clubEmailsMap, locale);
  const adminSupport = {
    ...pick(adminSupportMap, locale),
    columns: pick(adminSupportColumns, locale),
    priorities: pick(adminSupportPriorities, locale),
  };
  const notificationsPatch = pick(notificationsMap, locale);

  fillFromEn(clubs, en.clubs, locale, "clubs");
  fillFromEn(clubEmails, en.clubEmails, locale, "clubEmails");
  fillFromEn(adminSupport, en.adminSupport, locale, "adminSupport");

  data.clubs = clubs;
  data.clubEmails = clubEmails;
  data.adminSupport = adminSupport;
  data.notifications = { ...(data.notifications ?? {}), ...notificationsPatch };

  writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
}

