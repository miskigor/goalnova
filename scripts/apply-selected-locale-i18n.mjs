function pick(map, locale) {
  const out = {};
  for (const [key, langs] of Object.entries(map)) {
    out[key] = langs[locale] ?? langs.en;
  }
  return out;
}

function flatten(obj, prefix = "") {
  const out = {};
  for (const [key, value] of Object.entries(obj ?? {})) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === "object" && !Array.isArray(value)) {
      Object.assign(out, flatten(value, path));
    } else {
      out[path] = value;
    }
  }
  return out;
}

function setPath(obj, path, value) {
  const parts = path.split(".");
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i += 1) {
    if (cur[parts[i]] == null || typeof cur[parts[i]] !== "object") {
      cur[parts[i]] = {};
    }
    cur = cur[parts[i]];
  }
  cur[parts[parts.length - 1]] = value;
}

function warnMissing(map, locale, label) {
  for (const [key, langs] of Object.entries(map)) {
    if (langs[locale] == null) {
      console.warn(`Missing ${locale} translation: ${label}.${key} (copied from en)`);
    }
  }
}

function fillFromEn(built, enObj, locale, label) {
  const enFlat = flatten(enObj);
  const builtFlat = flatten(built);
  for (const [path, value] of Object.entries(enFlat)) {
    if (builtFlat[path] == null) {
      console.warn(`Missing ${locale} key vs en.json: ${label}.${path} (copied from en)`);
      setPath(built, path, value);
    }
  }
}

